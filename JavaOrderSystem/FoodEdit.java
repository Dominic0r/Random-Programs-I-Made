    public static void FillFields(){
        ordID = adm.orderID;
        for(int KeyFind : hm.prodList.keySet()){
            if(ordID == KeyFind){
                prodINF = hm.prodList.get(ordID);
                break;
            }
        }
        
        PIDField.setText(Integer.toString(ordID));
        PNField.setText(prodINF[0]);
        priceField.setText(prodINF[1]);
        qtyField.setText(prodINF[2]);
    }
    
    public static boolean isNotEmpty(){
        if(!PIDField.getText().isEmpty() && !PNField.getText().isEmpty() && !priceField.getText().isEmpty() && !qtyField.getText().isEmpty() ){
            return true;
        }else{
            return false;
        }
    }
    
