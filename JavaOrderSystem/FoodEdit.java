    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       if(isNotEmpty()){
        String[] newDat = prodINF.clone();
        int newID = Integer.parseInt(PIDField.getText());
        newDat[0] = PNField.getText();
        newDat[1] = priceField.getText();
        newDat[2] = qtyField.getText();
        hm.prodList.replace(newID, newDat);
        
        adm.dispUserTable();
        adm.dispFoodTable();
        JOptionPane.showMessageDialog(this, "Succesfully Applied Changes!");
        } else{
            JOptionPane.showMessageDialog(this, "Do not leave any fields empty!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

