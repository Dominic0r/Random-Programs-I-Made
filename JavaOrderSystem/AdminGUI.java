    public static void dispUserTable(){
        
        DefaultTableModel tblm = new DefaultTableModel();
        tblm.setColumnIdentifiers(new String[]{"ID", "Full Name", "Password", "Contact No", "Address", "Gender", "Type"});
        
        for(int PID : hm.acctList.keySet()){
            
            String[] PDat = hm.acctList.get(PID);
            tblm.addRow(new Object[]{PID, PDat[0], PDat[1], PDat[2], PDat[3], PDat[4], PDat[5] });
        }
        
        userAccTable.setModel(tblm);
        userAccTable.setDefaultEditor(Object.class, null);
    }
    
    public static void dispFoodTable(){
        DefaultTableModel tblm = new DefaultTableModel();
        tblm.setColumnIdentifiers(new String[]{"ID", "Food name", "Price", "Quantity"});
        
        for(int PID : hm.prodList.keySet()){
            
            String[] PDat = hm.prodList.get(PID);
            tblm.addRow(new Object[]{PID, PDat[0], PDat[1], PDat[2]});
        }
        
        foodListTable.setModel(tblm);
        foodListTable.setDefaultEditor(Object.class, null);
    }

