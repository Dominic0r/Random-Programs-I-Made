    private void DelFoodBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DelFoodBtnActionPerformed
        if(foodListTable.getSelectedRow()== -1){
            JOptionPane.showMessageDialog(this, "Select a product!");
        } else{
        int choice = JOptionPane.showConfirmDialog(this,  "Are you sure?","",JOptionPane.YES_NO_OPTION);
        if(choice == JOptionPane.YES_OPTION){
            int column = 0;
        int row = foodListTable.getSelectedRow();
        orderID = (int) foodListTable.getValueAt(row, column);
            
            hm.prodList.remove(orderID);
            dispFoodTable();
        }else{
            
        }
       }
    }//GEN-LAST:event_DelFoodBtnActionPerformed

