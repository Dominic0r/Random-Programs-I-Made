    public static void FillFields(){
        ordID = adm.orderID;
        for(int KeyFind : hm.acctList.keySet()){
            if(ordID == KeyFind){
                userData = hm.acctList.get(ordID);
                break;
            }
        }
        
        userIDDisplay.setText(Integer.toString(ordID));
        userFNDisplay.setText(userData[0]);
        userPWDisplay.setText(userData[1]);
        userContactDisplay.setText(userData[2]);
        userAddDisplay.setText(userData[3]);
        userGenderDisplay.setText(userData[4]);
        userTypeDisplay.setText(userData[5]);
    }
    
    public static boolean isNotEmpty(){
        if(!userIDDisplay.getText().isEmpty() && !userFNDisplay.getText().isEmpty() && !userPWDisplay.getText().isEmpty() && !userContactDisplay.getText().isEmpty() && !userAddDisplay.getText().isEmpty() && !userGenderDisplay.getText().isEmpty() && !userTypeDisplay.getText().isEmpty()) {
            return true;
        } else{
            return false;
        }
    }
    
