    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if(isNotEmpty()){
        String[] newDat = userData.clone();
        int newID = Integer.parseInt(userIDDisplay.getText());
        newDat[0] = userFNDisplay.getText();
        newDat[1] = userPWDisplay.getText();
        newDat[2] = userContactDisplay.getText();
        newDat[3] = userAddDisplay.getText();
        newDat[4] = userGenderDisplay.getText();
        newDat[5] = userTypeDisplay.getText();
        hm.acctList.replace(newID, newDat);
        
        adm.dispUserTable();
        adm.dispFoodTable();
        JOptionPane.showMessageDialog(this, "Succesfully Applied Changes!");
        } else{
            JOptionPane.showMessageDialog(this, "Do not leave any fields empty!");
        }
    }//GEN-LAST:event_jButton2ActionPerformed

